def main():
    items = []
    for doc_name, doc_type, chunks in DOCS:
        for section, content, params in chunks:
            items.append((doc_name, doc_type, section, f"{section}\n{content}", params))

    print(f"待入库片段：{len(items)} 块")

    vectors = []
    BATCH = 8
    try:
        for i in range(0, len(items), BATCH):
            batch = [it[3] for it in items[i:i + BATCH]]
            resp = embed(model="nomic-embed-text", input=batch)
            vectors.extend(resp["embeddings"])
            print(f"  embedded {min(i + BATCH, len(items))}/{len(items)}")
    except Exception as exc:
        print(f"embedding 失败：{exc}", file=sys.stderr)
        print("请确认 ollama 服务在跑，且已 pull nomic-embed-text", file=sys.stderr)
        sys.exit(1)

    with psycopg.connect(DSN) as conn:
        with conn.cursor() as cur:
            cur.execute("TRUNCATE device_manual_chunks;")
            for idx, (item, vec) in enumerate(zip(items, vectors)):
                doc_name, doc_type, section, content, params = item
                cur.execute(
                    """INSERT INTO device_manual_chunks
                       (chunk_uid, source, doc_type, section, content, params, embedding)
                       VALUES (%s, %s, %s, %s, %s, %s::jsonb, %s::vector)""",
                    (f"dm-{idx:03d}", doc_name, doc_type, section, content,
                     json.dumps(params, ensure_ascii=False),
                     "[" + ",".join(f"{v:.6f}" for v in vec) + "]"),
                )
        conn.commit()

    print(f"已入库 {len(items)} 块设备手册片段")


if __name__ == "__main__":
    main()
